/*
    Every constraint kind, generated by each backend from the line the Recipe Cockpit's filtered copy
    writes (#323), with every value checked against its bounds. faker-js runs through the real
    FakerJSRecipeProcessor. snowfakery is not installed in CI, so its copy is read with PyYAML and
    each expression rendered with Jinja and the real Faker, the two libraries snowfakery evaluates
    it with; date() and datetime() stand in for snowfakery's own, which parse an ISO string.
*/

const RECORD_COUNT = 250;

interface IConstraintCase {
    fieldApiName: string;
    target: IRecipeFieldConstraintTarget;
    stored: IStoredRecipeFieldConstraint;
}

const CONSTRAINT_CASES: IConstraintCase[] = [
    { fieldApiName: 'Whole__c', target: { fieldType: 'Number', precision: 5, scale: 0 }, stored: { min: '-5', max: '10' } },
    { fieldApiName: 'Amount__c', target: { fieldType: 'Currency', precision: 6, scale: 2 }, stored: { min: '0.01', max: '0.05' } },
    { fieldApiName: 'Rate__c', target: { fieldType: 'Percent', precision: 5, scale: 2 }, stored: { min: '-1.5' } },
    { fieldApiName: 'Code__c', target: { fieldType: 'Text', length: 20 }, stored: { min: '3', max: '8' } },
    { fieldApiName: 'Exact__c', target: { fieldType: 'TextArea' }, stored: { min: '5', max: '5' } },
    { fieldApiName: 'Notes__c', target: { fieldType: 'LongTextArea', length: 32768 }, stored: { max: '12' } },
    { fieldApiName: 'Due__c', target: { fieldType: 'Date' }, stored: { min: '-30d', max: '+90d' } },
    { fieldApiName: 'January__c', target: { fieldType: 'Date' }, stored: { min: '2024-01-01', max: '2024-01-31' } },
    { fieldApiName: 'Recent__c', target: { fieldType: 'DateTime' }, stored: { min: '-1d', max: 'today' } },
    { fieldApiName: 'Shift__c', target: { fieldType: 'DateTime' }, stored: { min: '2024-01-01T09:00:00Z', max: '2024-01-01T17:00:00Z' } },
    { fieldApiName: 'Since__c', target: { fieldType: 'DateTime' }, stored: { min: '2020-01-01' } }
];

function resolveCase(constraintCase: IConstraintCase): ResolvedRecipeFieldConstraint {
    const resolution = RecipeFieldConstraint.resolve(constraintCase.target, constraintCase.stored);
    if ( !( 'constraint' in resolution ) ) {
        throw new Error(`${constraintCase.fieldApiName}: ${resolution.refusal}`);
    }
    return resolution.constraint;
}

function buildConstrainedRecipe(fakerService: IRecipeFakerService): string {

    const sourceRecipe = [
        '- object: Gadget__c',
        '  nickname: Gadget__c_NickName',
        `  count: ${RECORD_COUNT}`,
        '  fields:',
        ...CONSTRAINT_CASES.map(constraintCase => `    ${constraintCase.fieldApiName}: placeholder`),
        ''
    ].join('\n');

    const expressionsByField = new Map(CONSTRAINT_CASES.map(constraintCase => [
        constraintCase.fieldApiName,
        fakerService.buildConstrainedExpression(constraintCase.target.fieldType, resolveCase(constraintCase))
    ]));

    const filterResult = RecipeCockpitRecipeWriter.buildFilteredRecipe(sourceRecipe, {
        excludedObjectApiNames: [],
        parentLookupsByObjectApiName: new Map(),
        constrainedExpressionsByObject: new Map([['Gadget__c', expressionsByField]])
    });

    if ( filterResult.isFiltered === false ) {
        throw new Error(filterResult.refusal.message);
    }
    expect(filterResult.appliedConstrainedExpressions).toHaveLength(CONSTRAINT_CASES.length);

    return filterResult.recipeText;

}

function toMilliseconds(dateBound: RecipeFieldConstraintDateBound, now: number): number {
    return RecipeFieldConstraint.toEpochMilliseconds(dateBound, new Date(now));
}

/*
    Why a generated value is outside its constraint, or undefined. A relative bound moves while the
    run runs, so it is measured from the test's start for "from" and its end for "to"; a backend that
    writes whole seconds is allowed the second it truncated.
*/
function findOutOfBoundsReason(constraintCase: IConstraintCase, value: unknown, startedAt: number, endedAt: number): string | undefined {

    const constraint = resolveCase(constraintCase);
    const text = String(value);

    if ( constraint.kind === 'number' ) {
        const decimals = text.split('.')[1] ?? '';
        return /^-?\d+(\.\d+)?$/.test(text) && Number(text) >= Number(constraint.min) && Number(text) <= Number(constraint.max) && decimals.length <= constraint.scale
            ? undefined
            : `${text} is not a number in [${constraint.min}, ${constraint.max}] with at most ${constraint.scale} decimals`;
    }

    if ( constraint.kind === 'length' ) {
        return typeof value === 'string' && /^[A-Za-z]*$/.test(value) && value.length >= constraint.min && value.length <= constraint.max
            ? undefined
            : `"${text}" is not letters of length ${constraint.min}-${constraint.max}`;
    }

    const fromMilliseconds = toMilliseconds(constraint.from, startedAt);
    const toMilliseconds_ = toMilliseconds(constraint.to, endedAt);

    if ( constraintCase.target.fieldType === 'Date' ) {
        const fromDate = new Date(fromMilliseconds).toISOString().slice(0, 10);
        const toDate = new Date(toMilliseconds_).toISOString().slice(0, 10);
        return /^\d{4}-\d{2}-\d{2}$/.test(text) && text >= fromDate && text <= toDate
            ? undefined
            : `${text} is not a date in [${fromDate}, ${toDate}]`;
    }

    const generatedMilliseconds = Date.parse(text.replace(/\+0000$/, 'Z'));
    return !Number.isNaN(generatedMilliseconds) && generatedMilliseconds >= fromMilliseconds - 1000 && generatedMilliseconds <= toMilliseconds_ + 1000
        ? undefined
        : `${text} is not a date-time in [${new Date(fromMilliseconds).toISOString()}, ${new Date(toMilliseconds_).toISOString()}]`;

}

function expectEveryValueInBounds(records: Array<Record<string, unknown>>, startedAt: number, endedAt: number) {

    expect(records).toHaveLength(RECORD_COUNT);

    const outOfBounds = CONSTRAINT_CASES.flatMap(constraintCase => records
        .map(record => findOutOfBoundsReason(constraintCase, record[constraintCase.fieldApiName], startedAt, endedAt))
        .filter(reason => reason !== undefined)
        .slice(0, 3)
        .map(reason => `${constraintCase.fieldApiName}: ${reason}`));

    expect(outOfBounds).toEqual([]);

}

describe('buildConstrainedExpression contract (#323)', () => {

    const backends: Array<[string, IRecipeFakerService]> = [
        ['faker-js', new FakerJSRecipeFakerService()],
        ['snowfakery', new SnowfakeryRecipeFakerService()]
    ];

    const fieldTypes = [...RECIPE_FIELD_CONSTRAINT_NUMBER_FIELD_TYPES, ...RECIPE_FIELD_CONSTRAINT_LENGTH_FIELD_TYPES, ...RECIPE_FIELD_CONSTRAINT_DATE_FIELD_TYPES];
    const constraintsByKind: Record<string, ResolvedRecipeFieldConstraint[]> = {
        number: [{ kind: 'number', min: '-1', max: '1', scale: 0 }, { kind: 'number', min: '0.5', max: '9.75', scale: 2 }],
        length: [{ kind: 'length', min: 0, max: 1 }],
        date: [{ kind: 'date', from: { relativeDays: -3 }, to: { relativeDays: 0 } }, { kind: 'date', from: { utcDateTime: '2024-01-01T00:00:00' }, to: { relativeDays: 5 } }]
    };

    test.each(backends)('%s writes every field type the cockpit constrains, as one expression the copy can carry', (unusedBackendName, fakerService) => {

        fieldTypes.forEach(fieldType => {
            const kind = RecipeFieldConstraint.getConstraintKind(fieldType) as string;
            constraintsByKind[kind].forEach(constraint => {
                const expression = fakerService.buildConstrainedExpression(fieldType, constraint);
                expect(RecipeCockpitRecipeWriter.checkConstrainedExpression(expression)).toBeUndefined();
            });
            Object.keys(constraintsByKind).filter(otherKind => otherKind !== kind).forEach(otherKind => {
                expect(() => fakerService.buildConstrainedExpression(fieldType, constraintsByKind[otherKind][0])).toThrow();
            });
        });

    });

    test.each(backends)('%s refuses a constraint on a type the cockpit does not constrain', (unusedBackendName, fakerService) => {
        ['Email', 'Phone', 'Url', 'Checkbox', 'Picklist', 'Lookup', 'Time'].forEach(fieldType => {
            expect(() => fakerService.buildConstrainedExpression(fieldType, constraintsByKind.length[0])).toThrow();
        });
    });

});

describe('every constraint generates inside its bounds (#323)', () => {

    test('faker-js, through the real recipe processor', async () => {

        const recipeText = buildConstrainedRecipe(new FakerJSRecipeFakerService());
        const temporaryFolderPath = fs.mkdtempSync(path.join(os.tmpdir(), 'constrained-expression-'));

        try {

            const recipeFilePath = path.join(temporaryFolderPath, 'recipe.yml');
            fs.writeFileSync(recipeFilePath, recipeText);

            const startedAt = Date.now();
            const generatedJson = await new FakerJSRecipeProcessor().generateFakeDataBySelectedRecipeFile(recipeFilePath);
            const endedAt = Date.now();

            expectEveryValueInBounds(( JSON.parse(generatedJson) as Array<{ fields: Record<string, unknown> }> ).map(record => record.fields), startedAt, endedAt);

        } finally {
            fs.rmSync(temporaryFolderPath, { recursive: true, force: true });
        }

    });

    test('the snowfakery copy loads in js-yaml as one string per field', () => {

        const recipeText = buildConstrainedRecipe(new SnowfakeryRecipeFakerService());
        const fields = ( yaml.load(recipeText) as Array<{ fields: Record<string, unknown> }> )[0].fields;

        CONSTRAINT_CASES.forEach(constraintCase => {
            expect(fields[constraintCase.fieldApiName]).toBe(new SnowfakeryRecipeFakerService().buildConstrainedExpression(constraintCase.target.fieldType, resolveCase(constraintCase)));
        });

    });

    PythonTestHarness.testRequiringModules('yaml', 'jinja2', 'faker')('snowfakery, read with PyYAML and rendered with Jinja and Faker', () => {

        const recipeText = buildConstrainedRecipe(new SnowfakeryRecipeFakerService());

        const startedAt = Date.now();
        const records = PythonTestHarness.runPython([
            'import datetime, json, sys, yaml, jinja2',
            'from faker import Faker',
            'environment = jinja2.Environment(block_start_string="${%", block_end_string="%}", variable_start_string="${{", variable_end_string="}}")',
            'environment.globals.update(fake=Faker(), date=datetime.date.fromisoformat, datetime=datetime.datetime.fromisoformat)',
            'request = json.load(sys.stdin)',
            'recipe = yaml.safe_load(request["recipeText"])[0]',
            'templates = {name: environment.from_string(value) for name, value in recipe["fields"].items()}',
            'print(json.dumps([{name: template.render() for name, template in templates.items()} for _ in range(recipe["count"])]))'
        ].join('\n'), { recipeText: recipeText }) as Array<Record<string, unknown>>;
        const endedAt = Date.now();

        expectEveryValueInBounds(records, startedAt, endedAt);

    });

});
